/** Truncate for admin UI hints (full text in title tooltip). */
export function truncateDefaultHint(text: string, maxLen = 120): string {
  const t = text.replace(/\s+/g, " ").trim();
  if (t.length <= maxLen) return t;
  return `${t.slice(0, maxLen)}…`;
}
